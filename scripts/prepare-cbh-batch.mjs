function issueUrl(value) {
  return /^https:\/\/(?:www\.)?marvel\.com\/comics\/issue\/\d+(?:\/|$)/i.test(String(value ?? ''));
}

function apiSeriesTitle(value) {
  return String(value ?? '').replace(/\s+\(\d{4}(?:\s*-\s*(?:\d{4}|Present))?\)\s*$/i, '').trim();
}

function apiSeriesYear(value) {
  const match = /\((\d{4})(?:\s*-\s*(?:\d{4}|Present))?\)\s*$/i.exec(String(value ?? ''));
  return match ? Number(match[1]) : null;
}

function reviewedSeriesNote(series, apiSeriesName) {
  if (series.id == null) {
    return `No repository metadata series was found for ${series.title}; the row remains unmatched.`;
  }
  const base = `Marvel series ${series.id} (${apiSeriesName}) is the reviewed metadata series for this source reference.`;
  const apiTitle = apiSeriesTitle(apiSeriesName);
  const titleNote = (
    apiTitle
    && normalizeTitle(apiTitle) !== normalizeTitle(series.title)
  ) ? ` The source title is ${series.title}; Marvel names the selected series ${apiTitle}.` : '';
  return `${base}${titleNote}${series.selectionNote ? ` ${series.selectionNote}` : ''}`;
}

function resolvedIssueTitle(item, sourceRow) {
  const title = String(item?.title ?? '').trim().replace(/\s+/g, ' ');
  const metadataNumber = sourceRow.metadataIssueNumber;
  if (metadataNumber == null || String(metadataNumber) === String(sourceRow.issueNumber)) return title;
  const escaped = String(metadataNumber).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const pattern = new RegExp(`#\\s*${escaped}(?=\\s|$)`, 'i');
  if (!pattern.test(title)) {
    throw new Error(`${sourceRow.sourceIssueReference} metadata title does not end in #${metadataNumber}`);
  }
  return title.replace(pattern, `#${sourceRow.issueNumber}`);
}

export function shouldPreserveApprovedMapping(existingMapping, {
  forceApproved = false,
  refreshApproved = false,
} = {}) {
  return (
    existingMapping?.reviewStatus === 'approved'
    && !forceApproved
    && !refreshApproved
  );
}

async function readExistingMapping(outputPath) {
  try {
    return JSON.parse(await readFile(outputPath, 'utf8'));
  } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
}

async function indexFrozenPackets(packetsDir) {
  let entries;
  try {
    entries = await readdir(packetsDir, { withFileTypes: true });
  } catch (error) {
    if (error?.code === 'ENOENT') return new Map();
    throw error;
  }

  const byInventoryId = new Map();
  for (const entry of entries
    .filter((candidate) => candidate.isFile() && candidate.name.endsWith('.json'))
    .sort((left, right) => left.name.localeCompare(right.name))) {
    const packet = JSON.parse(await readFile(path.join(packetsDir, entry.name), 'utf8'));
    const fileId = entry.name.slice(0, -'.json'.length);
    if (packet.id !== fileId) {
      throw new Error(`${entry.name} packet id must match its filename`);
    }
    const matches = byInventoryId.get(packet.inventoryId) ?? [];
    matches.push(packet);
    byInventoryId.set(packet.inventoryId, matches);
  }
  return byInventoryId;
}

export async function selectPreparationGuides(onlyIds, {
  packetsDir = PACKETS_DIR,
  inventoryPath = INVENTORY_PATH,
  manifestPath = MANIFEST_PATH,
} = {}) {
  if (onlyIds == null) return GUIDES;
  const requestedIds = Array.isArray(onlyIds) ? onlyIds : [...onlyIds];
  const legacyById = new Map(GUIDES.map((guide) => [guide.id, guide]));
  const packetsByInventoryId = await indexFrozenPackets(packetsDir);
  let inventory = null;
  let catalogEntries = null;
  const selected = [];

  for (const id of requestedIds) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) {
      throw new Error(`Invalid inventory id: ${id}`);
    }
    const matchingPackets = packetsByInventoryId.get(id) ?? [];
    if (matchingPackets.length > 1) {
      throw new Error(`Inventory id ${id} has multiple frozen packets`);
    }
    const packet = matchingPackets[0] ?? null;
    if (!packet) {
      const legacy = legacyById.get(id);
      if (!legacy) throw new Error(`Unknown inventory id: ${id}`);
      selected.push(legacy);
      continue;
    }

    inventory ??= JSON.parse(await readFile(inventoryPath, 'utf8'));
    const manifest = catalogEntries == null
      ? JSON.parse(await readFile(manifestPath, 'utf8'))
      : null;
    catalogEntries ??= Array.isArray(manifest?.lists) ? manifest.lists : [];
    const inventoryRecord = inventory.find((record) => record.id === id);
    if (!inventoryRecord) {
      throw new Error(`${packet.id} names unknown inventory id ${id}`);
    }
    validateFrozenPacket(packet, {
      expectedId: packet.id,
      inventoryRecord,
      catalogEntries,
    });
    selected.push({
      ...packet,
      isFrozenPacket: true,
      approvedSourceCount: packet.expectedCount,
      sourceUnavailable: false,
    });
  }

  return selected;
}

async function main() {
  const args = process.argv.slice(2);
  const forceApproved = args.includes('--force-approved');
  const refreshApproved = args.includes('--refresh-approved');
  if (forceApproved && refreshApproved) {
    throw new Error('Use either --force-approved or --refresh-approved, not both');
  }
  const onlyArgs = args.filter((arg) => arg.startsWith('--only='));
  if (onlyArgs.length > 1) throw new Error('Use --only once with a comma-separated inventory id list');
  const onlyIds = onlyArgs.length === 0
    ? null
    : onlyArgs[0].slice('--only='.length).split(',').map((id) => id.trim()).filter(Boolean);
  if (onlyIds?.length === 0) throw new Error('--only must name at least one inventory id');
  if (onlyIds && new Set(onlyIds).size !== onlyIds.length) {
    throw new Error('--only contains a duplicate inventory id');
  }
  const guides = await selectPreparationGuides(onlyIds);
  const { getJson } = createJsonFetcher();
  const getSeriesPage = async (url) => {
    for (let attempt = 0; ; attempt += 1) {
      try {
        return await getJson(url);
      } catch (error) {
        if (error?.status != null || attempt >= 2) throw error;
        await new Promise((resolve) => setTimeout(resolve, 1000 * (attempt + 1)));
      }
    }
  };
  const seriesIds = [...new Set(guides
    .flatMap((guide) => guide.rows)
    .map((row) => row.seriesId)
    .filter(Number.isInteger))];
  const seriesById = new Map();

  for (const seriesId of seriesIds) {
    const items = [];
    let firstPage = null;
    for (let offset = 0; ; offset += 200) {
      let body;
      try {
        body = await getSeriesPage(`${API}/series/${seriesId}/issues?limit=200&offset=${offset}`);
      } catch (error) {
        throw new Error(`Series ${seriesId} offset ${offset}: ${error.message}`, { cause: error });
      }
      firstPage ??= body;
      const page = Array.isArray(body?.items) ? body.items : [];
      items.push(...page);
      if (!body?.has_next || page.length === 0) break;
      if (items.length > 2000) throw new Error(`Series ${seriesId} paging did not terminate`);
    }
    seriesById.set(seriesId, { ...firstPage, items, has_next: false });
  }

  await mkdir(OUTPUT_DIR, { recursive: true });
  const summaries = [];

  for (const guide of guides) {
    const outputPath = path.join(OUTPUT_DIR, `${guide.id}.json`);
    const existingMapping = await readExistingMapping(outputPath);
    if (shouldPreserveApprovedMapping(existingMapping, { forceApproved, refreshApproved })) {
      summaries.push({
        id: guide.id,
        rows: existingMapping.rows.length,
        unmatched: 0,
        ambiguous: 0,
        skipped: true,
      });
      continue;
    }
    const candidateMetadata = [];
    const rows = guide.rows.map((sourceRow, index) => {
      const series = Object.values(SERIES).find((entry) =>
        entry.id === sourceRow.seriesId && entry.title === sourceRow.normalizedSeriesTitle);
      const body = sourceRow.seriesId == null ? null : seriesById.get(sourceRow.seriesId);
      const seriesItems = (Array.isArray(body?.items) ? body.items : []).filter((item) =>
        issueUrl(item.detailUrl));
      const matches = seriesItems.filter((item) => {
        if (sourceRow.candidateIssueId != null) return Number(item.id) === sourceRow.candidateIssueId;
        const metadataIssueNumber = sourceRow.metadataIssueNumber ?? sourceRow.issueNumber;
        if (metadataIssueNumber == null) return true;
        return String(item.issueNumber) === metadataIssueNumber;
      });
      const candidateSeriesTitle = apiSeriesTitle(body?.series_name);
      const candidateSeriesYear = apiSeriesYear(body?.series_name);
      const manualSeriesSelection = (
        normalizeTitle(candidateSeriesTitle) !== normalizeTitle(sourceRow.normalizedSeriesTitle)
      );
      const candidates = matches.map((item) => {
        const candidateSeriesId = item.seriesId ?? body?.series_id ?? null;
        return {
          id: item.id,
          title: candidateSeriesTitle,
          issueTitle: item.title,
          seriesTitle: candidateSeriesTitle,
          apiSeriesName: body.series_name,
          seriesId: candidateSeriesId,
          issueNumber: String(item.issueNumber),
          seriesYear: candidateSeriesYear,
          manualSeriesSelection,
          manualSeriesSelectionApproved: (
            manualSeriesSelection && sourceRow.manualSeriesSelectionApproved === true
          ),
          detailUrl: item.detailUrl,
          onSaleDate: item.onSaleDate,
        };
      });
      candidateMetadata.push(...candidates);

      return {
        sourcePosition: index + 1,
        sourceIssueReference: sourceRow.sourceIssueReference,
        sourceRangeReference: sourceRow.sourceRangeReference,
        normalizedSeriesTitle: sourceRow.normalizedSeriesTitle,
        seriesYear: sourceRow.seriesYear,
        issueNumber: sourceRow.issueNumber,
        ...(sourceRow.metadataIssueNumber == null
          ? {}
          : { metadataIssueNumber: sourceRow.metadataIssueNumber }),
        seriesId: sourceRow.seriesId,
        candidateIssueId: sourceRow.candidateIssueId,
        manualSeriesSelectionApproved: sourceRow.manualSeriesSelectionApproved,
        resolutionStatus: matches.length === 0 ? 'unmatched' : (matches.length > 1 ? 'ambiguous' : null),
        candidateIssueIds: candidates.map((candidate) => candidate.id),
        selectedIssueId: null,
        marvelIssueUrl: matches.length === 1 ? matches[0].detailUrl : null,
        resolvedIssueTitle: matches.length === 1 ? resolvedIssueTitle(matches[0], sourceRow) : null,
        note: `${reviewedSeriesNote(series ?? {
          id: sourceRow.seriesId,
          title: sourceRow.normalizedSeriesTitle,
        }, body?.series_name ?? 'metadata unavailable')}${sourceRow.selectionNote ? ` ${sourceRow.selectionNote}` : ''}`,
      };
    });

    const manifestProposal = guide.isFrozenPacket
      ? guide.proposedManifest
      : (MANIFEST_PROPOSALS[guide.id] ?? null);
    const coverRow = manifestProposal?.coverPosition
      ? rows[manifestProposal.coverPosition - 1]
      : null;
    const proposedManifest = guide.isFrozenPacket ? { ...manifestProposal } : (manifestProposal ? {
      id: guide.id,
      name: manifestProposal.name,
      description: manifestProposal.description,
      type: 'event',
      depth: 'complete',
      beginner: false,
      group: null,
      groupName: null,
      variant: null,
      sourceFile: `${guide.id}.md`,
      sourcePage: guide.sourceUrl,
      ...(guide.sourceSection ? { sourceSection: guide.sourceSection } : {}),
      sourceOrigin: "Compiled for this project from Comic Book Herald's guide",
      sourceLicense: null,
      out: `${guide.id.replaceAll('-', '_')}.json`,
      characters: manifestProposal.characters,
      keywords: manifestProposal.keywords,
      expect: rows.length,
      timeline: guide.proposedTimeline,
      coverIssueId: coverRow?.candidateIssueIds?.length === 1 ? coverRow.candidateIssueIds[0] : null,
      coverSourcePosition: manifestProposal.coverPosition,
      coverSourceReference: coverRow?.sourceIssueReference ?? null,
    } : {
      type: 'event',
      depth: 'complete',
      beginner: false,
      group: null,
      variant: null,
      timeline: guide.proposedTimeline,
      coverSourceReference: guide.proposedCoverReference,
    });

    const mapping = {
      id: guide.id,
      inventoryId: guide.inventoryId ?? guide.id,
      ...(guide.packetDigest ? { packetDigest: guide.packetDigest } : {}),
      sourceUrl: guide.sourceUrl,
      ...(guide.sourceSection ? { sourceSection: guide.sourceSection } : {}),
      sourceRetrievedAt: guide.sourceRetrievedAt ?? RETRIEVED_AT,
      sourceRetrievalStatus: guide.sourceUnavailable ? guide.sourceError : 'retrieved',
      approvedSourceCount: guide.sourceUnavailable
        ? null
        : (guide.approvedSourceCount ?? rows.length),
      excludedSourceReferences: guide.excludedSourceReferences ?? [],
      reviewStatus: guide.sourceUnavailable ? 'blocked-source-unavailable' : 'pending-independent-review',
      proposedManifest,
      candidateMetadata,
      rows,
    };
    const hasResolutionBlocker = (
      guide.sourceUnavailable
      || rows.some((row) => row.resolutionStatus === 'unmatched' || row.resolutionStatus === 'ambiguous')
    );
    const preparedMapping = hasResolutionBlocker
      ? mapping
      : await resolveMapping(mapping);
    const digestedMapping = guide.packetDigest
      ? { ...preparedMapping, mappingDigest: mappingDigestFor(preparedMapping) }
      : preparedMapping;
    let outputMapping = digestedMapping;
    if (existingMapping?.reviewStatus === 'approved' && refreshApproved) {
      if (hasResolutionBlocker) {
        throw new Error(`${guide.id} cannot preserve approval because its refreshed mapping is blocked`);
      }
      const existingIds = existingMapping.rows.map((row) => String(row.selectedIssueId));
      const refreshedIds = digestedMapping.rows.map((row) => String(row.selectedIssueId));
      if (existingIds.join('|') !== refreshedIds.join('|')) {
        throw new Error(`${guide.id} cannot preserve approval because its issue sequence changed`);
      }
      if (JSON.stringify(existingMapping.approvedManifest) !== JSON.stringify(digestedMapping.proposedManifest)) {
        throw new Error(`${guide.id} cannot preserve approval because its manifest fields changed`);
      }
      outputMapping = {
        ...digestedMapping,
        reviewStatus: 'approved',
        packetReview: existingMapping.packetReview,
        approvedManifest: existingMapping.approvedManifest,
        ...(existingMapping.relationshipReview
          ? { relationshipReview: existingMapping.relationshipReview }
          : {}),
      };
      if (!guide.packetDigest) delete outputMapping.proposedManifest;
    }
    const json = JSON.stringify(outputMapping, null, 2)
      .replace(/\u2013/g, '\\u2013').replace(/\u2014/g, '\\u2014');
    await writeFile(outputPath, `${json}\n`, 'utf8');
    summaries.push({
      id: guide.id,
      rows: rows.length,
      unmatched: rows.filter((row) => row.resolutionStatus === 'unmatched').length,
      ambiguous: rows.filter((row) => row.resolutionStatus === 'ambiguous').length,
    });
  }

  for (const summary of summaries) {
    if (summary.skipped) {
      console.log(`${summary.id}: approved mapping preserved`);
    } else {
      console.log(`${summary.id}: ${summary.rows} rows, ${summary.unmatched} unmatched, ${summary.ambiguous} ambiguous`);
    }
  }
}

const thisFile = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(thisFile)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
