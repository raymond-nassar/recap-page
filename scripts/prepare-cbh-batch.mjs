function issue(
  seriesKey,
  issueNumber,
  sourceIssueReference = null,
  sourceRangeReference = null,
  candidateIssueId = null,
  selectionNote = null,
  metadataIssueNumber = null,
) {
  const series = SERIES[seriesKey];
  if (!series) throw new Error(`Unknown series key: ${seriesKey}`);
  return {
    sourceIssueReference: sourceIssueReference ?? `${series.title} #${issueNumber}`,
    sourceRangeReference,
    normalizedSeriesTitle: series.title,
    seriesYear: series.year,
    issueNumber: issueNumber == null ? null : String(issueNumber),
    seriesId: series.id,
    candidateIssueId,
    manualSeriesSelectionApproved: Boolean(series.selectionNote),
    selectionNote,
    ...(metadataIssueNumber == null ? {} : { metadataIssueNumber: String(metadataIssueNumber) }),
  };
}

function issueWithMetadataNumber(
  seriesKey,
  sourceIssueNumber,
  metadataIssueNumber,
  sourceIssueReference,
  candidateIssueId = null,
  selectionNote = null,
) {
  return issue(
    seriesKey,
    sourceIssueNumber,
    sourceIssueReference,
    null,
    candidateIssueId,
    selectionNote ?? `Marvel metadata numbers the source's #${sourceIssueNumber} issue as #${metadataIssueNumber}; the source form remains the checklist display.`,
    metadataIssueNumber,
  );
}

function range(seriesKey, start, end, sourceRangeReference) {
  return Array.from(
    { length: end - start + 1 },
    (_, index) => issue(seriesKey, start + index, null, sourceRangeReference),
  );
}

function sequence(entries) {
  return entries.map(([seriesKey, issueNumber, sourceIssueReference, candidateIssueId, selectionNote]) =>
    issue(
      seriesKey,
      issueNumber,
      sourceIssueReference ?? null,
      null,
      candidateIssueId ?? null,
      selectionNote ?? null,
    ));
}

